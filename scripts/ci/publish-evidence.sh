#!/usr/bin/env bash
# Publishes generated CI output (test metrics, interoperability evidence) to the
# ci-evidence branch instead of committing it to main. main only takes reviewed
# pull requests; the site deploys and README badges read from ci-evidence.
#
# Usage: scripts/ci/publish-evidence.sh "<commit message>" <source>:<path> [<source>:<path> ...]
#   <path> is relative to the root of the ci-evidence branch.
#
# Environment:
#   IGNORE_FIELD  optional JSON field name (e.g. generatedAtUtc). When the only
#                 lines that changed contain it, nothing is published.
#
# Run from a checkout made by actions/checkout with a token that can push
# (permissions: contents: write). Prints published=true|false to $GITHUB_OUTPUT.
set -euo pipefail

BRANCH=ci-evidence
message="$1"; shift
[ "$#" -gt 0 ] || { echo "usage: $0 <message> <source>:<path>..." >&2; exit 2; }

repo_root="$(git rev-parse --show-toplevel)"
work="$(mktemp -d)"
trap 'git -C "$repo_root" worktree remove --force "$work" >/dev/null 2>&1 || true; rm -rf "$work"' EXIT

if git -C "$repo_root" fetch --quiet --depth=1 origin "$BRANCH" 2>/dev/null; then
  git -C "$repo_root" worktree add --quiet --detach "$work" FETCH_HEAD
else
  echo "Branch $BRANCH does not exist yet; creating it."
  git -C "$repo_root" worktree add --quiet --detach "$work"
  git -C "$work" checkout --quiet --orphan "$BRANCH"
  git -C "$work" rm -rfq . >/dev/null 2>&1 || true
  cat > "$work/README.md" <<'EOF'
# ci-evidence

Generated by CI; never edit by hand and never merge into main.
Test metrics, badges and published interoperability evidence live here so
main only carries reviewed changes. See scripts/ci/publish-evidence.sh.
EOF
  git -C "$work" add README.md
fi

for pair in "$@"; do
  src="${pair%%:*}"
  dest="${pair#*:}"
  mkdir -p "$work/$(dirname "$dest")"
  cp "$src" "$work/$dest"
  git -C "$work" add -- "$dest"
done

publish=true
if git -C "$work" diff --cached --quiet; then
  publish=false
  echo "Nothing changed; nothing to publish."
elif [ -n "${IGNORE_FIELD:-}" ] && git -C "$work" rev-parse --verify --quiet HEAD >/dev/null; then
  substantive=$(git -C "$work" diff --cached --unified=0 \
    | sed -n 's/^[+-]\([^+-]\)/\1/p' \
    | grep -vc "\"${IGNORE_FIELD}\"" || true)
  if [ "$substantive" = "0" ]; then
    publish=false
    echo "Only ${IGNORE_FIELD} changed; nothing to publish."
  fi
fi

if [ "$publish" = true ]; then
  git -C "$work" -c user.name="github-actions[bot]" \
    -c user.email="github-actions[bot]@users.noreply.github.com" \
    commit --quiet -m "$message"
  for attempt in 1 2 3; do
    if git -C "$work" push --quiet origin "HEAD:refs/heads/$BRANCH"; then
      break
    fi
    [ "$attempt" = 3 ] && { echo "Push to $BRANCH failed" >&2; exit 1; }
    echo "Push raced another publisher; rebasing and retrying."
    git -C "$work" fetch --quiet origin "$BRANCH"
    git -C "$work" rebase --quiet FETCH_HEAD
  done
  echo "Published to $BRANCH."
fi

[ -n "${GITHUB_OUTPUT:-}" ] && echo "published=$publish" >> "$GITHUB_OUTPUT"
exit 0
